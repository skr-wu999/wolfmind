import { afterEach, beforeEach, expect, test, vi } from 'vitest'
import { createMockGameAdapter } from '../src/features/game/mockGameAdapter'
import type { GameCommand } from '../src/features/game/types'

beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(new Date('2026-10-11T06:00:00Z')) })
afterEach(() => vi.useRealTimers())
const vote = (version: number, targetSeatNo = 4): GameCommand => ({ commandId: 'vote-1', expectedVersion: version, actionType: 'VOTE', params: { targetSeatNo } })

test('discussion has no vote permission and contains no other player identities', async () => {
  const adapter = createMockGameAdapter()
  const view = await adapter.get('demo')
  expect(view.players).toHaveLength(9)
  expect(view.players.every(p => p.disclosedRole === undefined)).toBe(true)
  expect(view.permissions).toEqual([])
  expect(view.wolfMessages).toEqual([])
  await expect(adapter.submit('demo', vote(view.version))).rejects.toThrow('当前阶段')
  await expect(adapter.get('online-id')).rejects.toThrow('在线服务')
})
test('AI deltas are transient and a completed public speech is recorded exactly once', async () => {
  const adapter = createMockGameAdapter(), updates: number[] = []
  const initial = await adapter.get('demo')
  const stop = adapter.subscribe('demo', view => updates.push(view.version))
  await vi.advanceTimersByTimeAsync(480)
  const streaming = await adapter.get('demo')
  expect(streaming.preview?.content.length).toBeGreaterThan(0)
  expect(streaming.version).toBe(initial.version)
  expect(streaming.messages).toHaveLength(2)
  await vi.advanceTimersByTimeAsync(10000)
  const final = await adapter.get('demo')
  expect(final.preview).toBeNull()
  expect(final.messages.filter(m => m.id === 'speech-3')).toHaveLength(1)
  expect(final.version).toBe(initial.version + 1)
  stop(); expect(vi.getTimerCount()).toBe(0)
})
test('vote validates eligibility, idempotency and version without resolving a death', async () => {
  const adapter = createMockGameAdapter(), view = await adapter.scenario('demo', 'voting')
  await expect(adapter.submit('demo', vote(view.version, 6))).rejects.toThrow('目标')
  await expect(adapter.submit('demo', vote(view.version - 1))).rejects.toThrow('状态已更新')
  const command = vote(view.version), accepted = await adapter.submit('demo', command)
  expect(accepted.submitted).toContain('投票已提交')
  expect(accepted.players.find(p => p.seatNo === 4)?.alive).toBe(true)
  expect(accepted.result).toBeNull()
  expect(await adapter.submit('demo', command)).toEqual(accepted)
  await expect(adapter.submit('demo', { ...command, params: { targetSeatNo: 2 } })).rejects.toThrow('同一命令')
  await expect(adapter.submit('demo', { ...vote(accepted.version), commandId: 'vote-2' })).rejects.toThrow('当前阶段')
})
test('deadline expires without locally advancing the phase or submitting a skip', async () => {
  const adapter = createMockGameAdapter(), view = await adapter.scenario('demo', 'voting')
  await vi.advanceTimersByTimeAsync(90001)
  await expect(adapter.submit('demo', vote(view.version))).rejects.toThrow('时间已结束')
  expect((await adapter.get('demo')).phase).toBe('DAY_VOTING')
})
test('seer result belongs only to the private projection and waiting roles have no skills', async () => {
  const adapter = createMockGameAdapter(), view = await adapter.scenario('demo', 'seer')
  const accepted = await adapter.submit('demo', { commandId: 'inspect', expectedVersion: view.version, actionType: 'SEER_INSPECT', params: { targetSeatNo: 2 } })
  expect(accepted.privateResult?.title).toBe('真相浮现')
  expect(accepted.privateRecords).toHaveLength(2)
  expect(accepted.records.some(r => r.text.includes('阵营'))).toBe(false)
  expect(accepted.players.find(p => p.seatNo === 2)?.disclosedRole).toBeUndefined()
  for (const scenario of ['villager', 'hunter-wait', 'resolving']) {
    const waiting = await adapter.scenario('demo', scenario)
    expect(waiting.permissions).toEqual([])
    expect(waiting.privateRecords).toEqual([])
    expect(waiting.wolfMessages).toEqual([])
  }
})
test('witch uses only the authorized rescue target and consumes both choices after one drug', async () => {
  const adapter = createMockGameAdapter(), view = await adapter.scenario('demo', 'witch')
  await expect(adapter.submit('demo', { commandId: 'wrong', expectedVersion: view.version, actionType: 'WITCH_SAVE', params: { targetSeatNo: 2 } })).rejects.toThrow('目标')
  const accepted = await adapter.submit('demo', { commandId: 'save', expectedVersion: view.version, actionType: 'WITCH_SAVE', params: { targetSeatNo: 8 } })
  expect(accepted.permissions).toEqual([])
  expect(accepted.phase).toBe('NIGHT_ACTION')
  expect(accepted.players.find(p => p.seatNo === 8)?.alive).toBe(true)
  await expect(adapter.submit('demo', { commandId: 'poison', expectedVersion: accepted.version, actionType: 'WITCH_POISON', params: { targetSeatNo: 1 } })).rejects.toThrow('当前阶段')
})
test('wolf projection discloses only its team and its chat never enters public messages', async () => {
  const adapter = createMockGameAdapter(), view = await adapter.scenario('demo', 'wolf')
  expect(view.players.filter(p => p.disclosedRole).map(p => p.seatNo)).toEqual([2, 7, 9])
  expect(view.permissions.find(p => p.type === 'WOLF_KILL')?.targets).not.toContain(2)
  const accepted = await adapter.submit('demo', { commandId: 'chat', expectedVersion: view.version, actionType: 'WOLF_CHAT', params: { content: '先听 1 号的判断。' } })
  expect(accepted.wolfMessages).toHaveLength(2)
  expect(accepted.messages).toEqual(view.messages)
  expect(accepted.records).toEqual(view.records)
  expect(accepted.permissions.find(p => p.type === 'WOLF_KILL')).toBeDefined()
})
test('hunter can react while dead only with an explicit permission, and guard remains a preview', async () => {
  const adapter = createMockGameAdapter(), view = await adapter.scenario('demo', 'hunter')
  expect(view.me.alive).toBe(false)
  const accepted = await adapter.submit('demo', { commandId: 'shot', expectedVersion: view.version, actionType: 'HUNTER_SHOOT', params: { giveUp: true } })
  expect(accepted.submitted).toBeTruthy()
  expect(accepted.players.find(p => p.seatNo === 1)?.alive).toBe(true)
  const guard = await adapter.scenario('demo', 'guard')
  expect(guard.permissions[0]?.type).toBe('GUARD_PREVIEW')
  expect(guard.permissions[0]?.targets).not.toContain(2)
})
test('session reload restores the same deadline and a completed action, not a fresh day', async () => {
  const data = new Map<string, string>(), storage = { getItem: (key: string) => data.get(key) || null, setItem: (key: string, value: string) => { data.set(key, value) } }
  const adapter = createMockGameAdapter(storage), voting = await adapter.scenario('demo', 'voting')
  await vi.advanceTimersByTimeAsync(12000)
  expect((await createMockGameAdapter(storage).get('demo')).deadline).toBe(voting.deadline)
  await adapter.submit('demo', vote(voting.version))
  const restored = await createMockGameAdapter(storage).get('demo')
  expect(restored.phase).toBe('DAY_VOTING')
  expect(restored.permissions).toEqual([])
  expect(restored.submitted).toContain('投票已提交')
})
